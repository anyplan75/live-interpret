const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const read = (rel) => fs.readFileSync(path.join(root, rel), "utf8");

test("the web settings page starts a broadcast without picking a device", () => {
  const page = read("docs/desk/index.html");
  const client = read("docs/js/desk-client.js");
  assert.match(page, /통역 설정/);
  assert.match(page, /id="start"/);
  assert.match(page, /id="stop"/);
  assert.match(page, /id="langs"/);
  assert.match(page, /id="showName"/);
  assert.match(page, /id="onAir"/);
  assert.match(page, /id="live"/);
  assert.match(page, /id="koStack"/);
  assert.match(page, /id="log"/);
  assert.match(page, /id="sensitivity"/);
  assert.match(page, /id="sessionKind"/);
  assert.match(page, /id="phoneCount"/);
  assert.match(page, /id="pickBulletin"/);
  assert.match(page, /id="inputs"/);
  assert.match(page, /id="watchLangs"/);
  assert.match(page, /id="confirmHint"/);
  assert.match(page, /id="opsBar"/);
  assert.match(page, /연결 상태/);
  assert.match(page, /details class="setup"/);
  assert.match(page, /시작 전 준비/);
  assert.match(page, /이번 방송 차감/);
  assert.match(page, /id="operator"/);
  assert.match(page, /id="testPeriod"/);
  assert.match(page, /남은 충전금/);
  assert.match(page, /불러오는 중/);
  assert.match(page, /liDeskSession/);
  assert.match(page, /history\.replaceState/);
  assert.match(page, /width:\s*fit-content/);
  assert.match(page, /class="chips"/);
  assert.match(page, /class="monitor"/);
  assert.match(page, /class="cost-mid"|id="costHead"/);
  assert.match(page, /panel conn|class="panel conn"/);
  assert.match(page, /setup-info/);
  assert.match(page, /max-width:\s*1180px/);
  assert.match(page, /보고 싶은 언어만/);
  assert.doesNotMatch(page, /<select\b/);
  assert.doesNotMatch(page, /id="startConfirm"/);
  assert.doesNotMatch(page, /id="confirmCancel"/);
  const liveAt = page.indexOf('id="live"');
  const inputsAt = page.indexOf('id="inputs"');
  const langsAt = page.indexOf('id="langs"');
  const bulletinAt = page.indexOf('id="pickBulletin"');
  const watchAt = page.indexOf('id="watchLangs"');
  const connAt = page.indexOf("연결 상태");
  const costAt = page.indexOf('id="costHead"');
  const opsAt = page.indexOf('id="opsBar"');
  assert.ok(liveAt > 0 && inputsAt > liveAt);
  assert.ok(watchAt > 0 && watchAt < inputsAt);
  assert.ok(langsAt > inputsAt && bulletinAt > 0);
  assert.ok(connAt > 0 && langsAt > connAt);
  assert.ok(costAt > 0 && costAt < liveAt);
  assert.ok(opsAt > 0 && opsAt < costAt);
  assert.ok(page.indexOf("시작 전 준비") < langsAt || page.indexOf('id="pickBulletin"') > 0);
  assert.match(client, /room\/desired/);
  assert.match(client, /room\/status/);
  assert.match(client, /withRev/);
  assert.match(client, /id="live"|getElementById\("live"\)/);
  assert.match(client, /confirmStart/);
  assert.match(client, /startArmed/);
  assert.match(client, /watchLangs|watched/);
  assert.match(client, /sessionStorage/);
  assert.match(client, /personText/);
  assert.match(client, /chip on|className = .*chip/);
  assert.match(client, /paintPhoneCount/);
  assert.match(client, /시작확인/);
  assert.doesNotMatch(page, /id="device"|설교|교회/);
  assert.doesNotMatch(client, /console\.(log|info|debug)/);
  assert.doesNotMatch(client, /location\.hash/);
});
